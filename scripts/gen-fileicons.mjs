// Embeds the vendored JetBrains SVGs into src/ui/fileicons-data.ts: frames can only import code, not .svg files.
// Run from the repository root after changing src/vendor/jetbrains-icons: node scripts/gen-fileicons.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = 'src/vendor/jetbrains-icons'
const names = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()
const lines = names.map((f) => `  ${JSON.stringify(f.slice(0, -4))}: ${JSON.stringify(readFileSync(`${dir}/${f}`, 'utf8').trim())},`)
const out = `// Generated by scripts/gen-fileicons.mjs from src/vendor/jetbrains-icons (JetBrains, Apache-2.0); do not edit.\nexport const ICON_SVG: Record<string, string> = {\n${lines.join('\n')}\n}\n`
writeFileSync('src/ui/fileicons-data.ts', out.replace(/\n/g, '\r\n'))
